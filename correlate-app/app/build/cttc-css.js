#!/usr/bin/env node
/**
 * The app's one stylesheet of cttc's rules (br-STYLE-000001-sJpO9KMY), in
 * cttc's own order.
 *
 * Each area keeps its ported rules in its own file (`components.css`,
 * `shell.css`, ...), in blocks headed `cttc style.css:A-B` (cttc's lines A to
 * B) or `ours: <reason>`. Loaded one file after another, rules of equal
 * specificity would win by file order, not by cttc's: the sidebar's
 * `.ab-group button` came after cttc's `button:hover` and hid its hover border
 * (found by the parity check, STEP-000092-sJpO9KMY). This script merges every
 * block into `renderer/src/theme/cttc.generated.css`, sorted by its cttc line;
 * a block of ours stays right after the cttc block it follows. The app loads
 * that file only. `node build/cttc-css.js` writes it; a test keeps it in step.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const APP = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SRC = path.join(APP, "renderer", "src");

/** The stylesheets of ported rules, from `renderer/src`. */
export const SOURCES = [
  "components/components.css",
  "shell/shell.css",
  "statusbar/statusbar.css",
  "menubar/menubar.css",
  "streams/streams.css",
  "charts/charts.css",
  "logs/logs.css",
];

/** Where the merged stylesheet goes. */
export const OUTPUT = path.join(SRC, "theme", "cttc.generated.css");

const BLOCK =
  /\/\* (cttc style\.css:(\d+)-(\d+)|ours:[\s\S]*?) \*\/([\s\S]*?)(?=\/\* (?:cttc style\.css:|ours:)|$)/g;

/**
 * @typedef {{ file: string, head: string, from?: number, to?: number, key: number, body: string }} Block
 */

/** @returns {Block[]} every block of every source, with its sort key */
export function blocks() {
  /** @type {Block[]} */
  const all = [];
  for (const file of SOURCES) {
    const text = readFileSync(path.join(SRC, file), "utf8");
    let key = 0;
    let n = 0;
    for (const m of text.matchAll(BLOCK)) {
      n += 1;
      const from = m[2] ? Number(m[2]) : undefined;
      // A block of ours follows the cttc block before it, in its file's order.
      key = from ?? key + n / 1000;
      all.push({
        file,
        head: m[1] ?? "",
        from,
        to: m[3] ? Number(m[3]) : undefined,
        key,
        // The next block's section title trails this one in its file: left out.
        body: (m[4] ?? "").replace(/(\s*\/\*(?:(?!\*\/)[\s\S])*\*\/\s*)+$/, "").trim(),
      });
    }
  }
  const cttc = all
    .filter((b) => b.from !== undefined)
    .sort((a, b) => (a.from ?? 0) - (b.from ?? 0));
  for (let i = 1; i < cttc.length; i += 1) {
    const a = cttc[i - 1];
    const b = cttc[i];
    if (a && b && (b.from ?? 0) <= (a.to ?? 0)) {
      throw new Error(`cttc lines ported twice: ${a.file} ${a.head} and ${b.file} ${b.head}`);
    }
  }
  return all.sort((a, b) => a.key - b.key);
}

/** The merged stylesheet's text. */
export function generated() {
  return [
    "/* Generated by build/cttc-css.js from the ported stylesheets; do not edit.",
    "   br-STYLE-000001-sJpO9KMY: every block in cttc's own order; regenerate",
    "   with `npm run css`. */",
    ...blocks().map((b) => `\n/* ${b.file}: ${b.head.split("\n")[0]} */\n${b.body}`),
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generated());
  console.log(`wrote ${path.relative(APP, OUTPUT)} (${blocks().length} blocks)`);
}
